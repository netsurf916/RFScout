#!/usr/bin/env python3
"""Generate RFScout's curated surveillance evidence database and advisory OUI report."""

import csv
import pathlib
import re
import sys

ROOT = pathlib.Path(__file__).resolve().parents[1]
WIRELESS_SERVICE = ROOT / "main" / "services" / "wireless"
SOURCE = ROOT / "data" / "surveillance_signatures.csv"
IEEE_SOURCE = WIRELESS_SERVICE / "oui_database.inc"
OUT = WIRELESS_SERVICE / "surveillance_signatures.inc"
REPORT = ROOT / "data" / "surveillance_oui_validation.csv"
GENERATED_HEADER = WIRELESS_SERVICE / "surveillance_generated.h"

CLASS_MAP = {
    "ALPR": "SURVEILLANCE_ALPR",
    "BODY": "SURVEILLANCE_BODY_CAMERA",
    "DRONE": "SURVEILLANCE_DRONE",
    "CAM": "SURVEILLANCE_CAMERA",
    "GLASS": "SURVEILLANCE_SMART_GLASSES",
    "AUDIO": "SURVEILLANCE_AUDIO",
    "OTHER": "SURVEILLANCE_OTHER",
}
SIGNAL_TYPES = {
    "oui",
    "name_contains",
    "name_prefix",
    "company_id",
    "service_uuid16",
    "service_uuid128",
    "remote_id",
}
IEEE_RECORD_RE = re.compile(
    r'^\s*\{\s*0x([0-9A-Fa-f]{6})\s*,\s*"((?:\\.|[^"])*)"\s*\},\s*$'
)


def load_ieee_snapshot() -> dict[int, str]:
    """Load exact MA-L ownership for advisory comparison with curated /24 prefixes."""
    result = {}
    if not IEEE_SOURCE.exists():
        print("warning: IEEE snapshot unavailable; advisory validation empty", file=sys.stderr)
        return result
    with IEEE_SOURCE.open(encoding="utf-8") as stream:
        for line in stream:
            match = IEEE_RECORD_RE.match(line)
            if match is not None:
                result[int(match.group(1), 16)] = match.group(2)
    return result


def normalized_hex(value: str, digits: int, line: int) -> str:
    result = re.sub(r"[^0-9A-Fa-f]", "", value).upper()
    if len(result) != digits:
        raise RuntimeError(f"invalid {digits * 4}-bit value at line {line}: {value}")
    return result


def c_string(value: str) -> str:
    return '"' + value.replace("\\", "\\\\").replace('"', '\\"') + '"'


def main() -> None:
    ieee = load_ieee_snapshot()
    rows = []
    signatures = {}
    oui_report = []

    with SOURCE.open(newline="", encoding="utf-8") as stream:
        for line, row in enumerate(csv.DictReader(stream), start=2):
            kind = row["type"].strip().upper()
            brand = row["brand"].strip()
            signal = row["signal"].strip().lower()
            value = row["value"].strip()
            evidence = row["evidence"].strip()
            if kind not in CLASS_MAP:
                raise RuntimeError(f"unsupported surveillance class at line {line}: {kind}")
            if not brand:
                raise RuntimeError(f"missing brand at line {line}")
            if signal not in SIGNAL_TYPES:
                raise RuntimeError(f"unsupported signal at line {line}: {signal}")
            try:
                weight = int(row["weight"])
            except ValueError as exc:
                raise RuntimeError(f"invalid weight at line {line}: {row['weight']}") from exc
            if weight not in {1, 2, 4}:
                raise RuntimeError(f"weight must be 1, 2, or 4 at line {line}: {weight}")

            key = (kind, brand)
            if key not in signatures:
                signatures[key] = len(signatures) + 1
            signature = signatures[key]

            if signal == "oui":
                value = normalized_hex(value, 6, line)
                prefix = int(value, 16)
                owner = ieee.get(prefix, "")
                oui_report.append((kind, brand, value, weight, evidence, owner))
            elif signal in {"company_id", "service_uuid16"}:
                value = normalized_hex(value, 4, line)
            elif signal == "service_uuid128":
                value = normalized_hex(value, 32, line)
            elif signal == "remote_id" and value not in {"0", "1"}:
                raise RuntimeError(f"remote_id value must be 0 or 1 at line {line}")

            rows.append((len(rows) + 1, kind, brand, signature, signal, value, weight, evidence))

    lines = [
        "/* Generated by tools/update_surveillance.py; do not edit manually. */",
        "/* Compact runtime form of data/surveillance_signatures.csv. */",
        "static const surveillance_signature_info_t surveillance_signature_info[] =",
        "{",
        '    { SURVEILLANCE_NONE, "" },',
    ]
    for (kind, brand), _signature in signatures.items():
        lines.append(f"    {{ {CLASS_MAP[kind]}, {c_string(kind + '/' + brand)} }},")
    lines += [
        "};",
        "#define SURVEILLANCE_SIGNATURE_COUNT \\",
        "    ( sizeof( surveillance_signature_info ) / sizeof( surveillance_signature_info[ 0 ] ) )",
        "",
        "static const surveillance_evidence_record_t surveillance_evidence_records[] =",
        "{",
    ]
    signal_map = {
        "oui": "SURVEILLANCE_SIGNAL_OUI",
        "name_contains": "SURVEILLANCE_SIGNAL_NAME_CONTAINS",
        "name_prefix": "SURVEILLANCE_SIGNAL_NAME_PREFIX",
        "company_id": "SURVEILLANCE_SIGNAL_COMPANY_ID",
        "service_uuid16": "SURVEILLANCE_SIGNAL_SERVICE_UUID16",
        "service_uuid128": "SURVEILLANCE_SIGNAL_SERVICE_UUID128",
        "remote_id": "SURVEILLANCE_SIGNAL_REMOTE_ID",
    }
    for record_id, kind, _brand, signature, signal, value, weight, _evidence in rows:
        if signal in {"name_contains", "name_prefix", "service_uuid128"}:
            text = c_string(value)
            numeric = "0U"
        elif signal == "remote_id":
            text = "NULL"
            numeric = f"{int(value)}U"
        else:
            text = "NULL"
            numeric = f"UINT64_C( 0x{value} )" if len(value) <= 16 else "0U"
        lines.append(
            f"    {{ {record_id}U, {signature}U, {CLASS_MAP[kind]}, "
            f"{signal_map[signal]}, {weight}U, {numeric}, {text} }},"
        )
    lines += [
        "};",
        "#define SURVEILLANCE_EVIDENCE_RECORD_COUNT \\",
        "    ( sizeof( surveillance_evidence_records ) / sizeof( surveillance_evidence_records[ 0 ] ) )",
        "",
    ]
    OUT.write_text("\n".join(lines), encoding="utf-8")

    evidence_words = (len(rows) + 31) // 32
    generated_header = [
        "/* Generated by tools/update_surveillance.py; do not edit manually. */",
        "#pragma once",
        "",
        f"#define RFSCOUT_SURVEILLANCE_EVIDENCE_WORD_COUNT {evidence_words}U",
        "",
    ]
    GENERATED_HEADER.write_text("\n".join(generated_header), encoding="utf-8")

    oui_report.sort(key=lambda item: int(item[2], 16))

    with REPORT.open("w", newline="", encoding="utf-8") as stream:
        writer = csv.writer(stream)
        writer.writerow(
            ("type", "brand", "oui", "weight", "evidence", "ieee_owner", "registry_status")
        )
        for kind, brand, value, weight, evidence, owner in oui_report:
            status = "present" if owner else "not-in-current-ma-l-snapshot"
            writer.writerow((kind, brand, value, weight, evidence, owner, status))
            if not owner:
                print(
                    f"notice: {value} {kind}/{brand} absent from current MA-L snapshot; review only",
                    file=sys.stderr,
                )

    print(
        f"wrote {len(rows)} surveillance evidence records "
        f"({evidence_words} x 32-bit case words) to {OUT}"
    )
    print(f"wrote advisory IEEE cross-reference report to {REPORT}")


if __name__ == "__main__":
    main()
