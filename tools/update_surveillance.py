#!/usr/bin/env python3
"""Generate RFScout's compiled surveillance signature table.

The curated CSV decides what constitutes a surveillance signature. The current
IEEE MA-L registry is used only to validate those prefixes; an IEEE vendor name
never creates a surveillance classification on its own.
"""

import csv
import io
import pathlib
import re
import sys
import urllib.request

IEEE_URL = "https://standards-oui.ieee.org/oui/oui.csv"
ROOT = pathlib.Path(__file__).resolve().parents[1]
SOURCE = ROOT / "data" / "surveillance_signatures.csv"
OUT = ROOT / "main" / "surveillance_signatures.inc"
REPORT = ROOT / "data" / "surveillance_oui_validation.csv"
USER_AGENT = "RFScout surveillance signature validator"

CLASS_MAP = {"ALPR":"SURVEILLANCE_FLOCK","BODY":"SURVEILLANCE_BODY_CAMERA","DRONE":"SURVEILLANCE_DRONE","CAM":"SURVEILLANCE_CAMERA","GLASS":"SURVEILLANCE_SMART_GLASSES"}
ID_MAP = {("ALPR","Flock"):"SURVEILLANCE_SIGNATURE_FLOCK",("BODY","Axon"):"SURVEILLANCE_SIGNATURE_AXON",("DRONE","DJI+"):"SURVEILLANCE_SIGNATURE_DRONE_DJI_PLUS",("CAM","Ring"):"SURVEILLANCE_SIGNATURE_RING",("GLASS","Meta+"):"SURVEILLANCE_SIGNATURE_GLASSES_META_PLUS"}


def download_ieee() -> dict[int, str]:
    """Return current IEEE MA-L organization names indexed by 24-bit prefix."""
    request = urllib.request.Request(IEEE_URL, headers={"User-Agent": USER_AGENT})
    with urllib.request.urlopen(request, timeout=45) as response:
        text = response.read().decode("utf-8-sig")
    result = {}
    for row in csv.DictReader(io.StringIO(text)):
        assignment = row.get("Assignment", "").replace("-", "").strip()
        if len(assignment) == 6:
            result[int(assignment, 16)] = row.get("Organization Name", "").strip()
    if len(result) < 30000:
        raise RuntimeError(f"IEEE registry unexpectedly small: {len(result)}")
    return result


def main() -> None:
    """Validate the curated CSV and generate the compact compiled C table."""
    ieee = download_ieee()
    rows = []
    with SOURCE.open(newline="", encoding="utf-8") as stream:
        for line, row in enumerate(csv.DictReader(stream), start=2):
            kind = row["type"].strip().upper()
            brand = row["brand"].strip()
            raw_oui = re.sub(r"[^0-9A-Fa-f]", "", row["oui"])
            evidence = row["evidence"].strip()
            if kind not in CLASS_MAP or (kind, brand) not in ID_MAP:
                raise RuntimeError(f"unsupported signature at line {line}: {kind}/{brand}")
            if len(raw_oui) != 6:
                raise RuntimeError(f"invalid OUI at line {line}: {row['oui']}")
            prefix = int(raw_oui, 16)
            rows.append((prefix, kind, brand, evidence, ieee.get(prefix, "")))

    rows.sort(key=lambda item: item[0])
    lines = ["/* Generated by tools/update_surveillance.py; do not edit manually. */","static const surveillance_oui_signature_t surveillance_oui_signatures[] =","{"]
    for prefix, kind, brand, _evidence, _owner in rows:
        lines.append("    { 0x%06XU, %s, %s }," % (prefix, CLASS_MAP[kind], ID_MAP[(kind, brand)]))
    lines += ["};","#define SURVEILLANCE_OUI_SIGNATURE_COUNT \\","    ( sizeof( surveillance_oui_signatures ) / sizeof( surveillance_oui_signatures[ 0 ] ) )",""]
    OUT.write_text("\n".join(lines), encoding="utf-8")

    with REPORT.open("w", newline="", encoding="utf-8") as stream:
        writer = csv.writer(stream)
        writer.writerow(("type","brand","oui","evidence","ieee_owner","registry_status"))
        for prefix, kind, brand, evidence, owner in rows:
            writer.writerow((kind, brand, f"{prefix:06X}", evidence, owner, "present" if owner else "missing"))
            if not owner:
                print(f"warning: {prefix:06X} {kind}/{brand}: absent from current IEEE MA-L registry", file=sys.stderr)

    print(f"wrote {len(rows)} curated surveillance signatures to {OUT}")
    print(f"wrote IEEE validation report to {REPORT}")


if __name__ == "__main__":
    main()
